'use strict';
// Uhhhhhh Reanimate MOVESET factory generator.
// The module uses AnimLib.Animator and its weighted Transform interpolation.
const ROLES=Object.freeze(['idle','walk','run','jump','fall','climb','sit']);
function slug(value){
 const result=String(value||'').trim().replace(/[^A-Za-z0-9_ -]/g,'_').replace(/\s+/g,'_').slice(0,44);
 return result||'Custom';
}
function lua(value){
 // Restrict all generated identifiers and displayed labels to printable ASCII.
 const sanitized=String(value||'').replace(/[^ -~]/g,' ').slice(0,100);
 return JSON.stringify(sanitized);
}
function makeMoveset({name,roles,music=false,fade=0.20,runSpeed=16}){
 if(typeof name!=='string'||name.trim().length<2||name.trim().length>64)
  throw Error('Moveset name must be 2-64 characters.');
 if(!roles?.idle||!roles?.walk)throw Error('Idle and Walk animations are required.');
 const safe=slug(name),assets={};
 for(const role of ROLES)if(roles[role])assets[role]='MRH_'+safe+'_'+role+'.anim';
 if(music)assets.music='MRH_'+safe+'_music.mp3';
 fade=Number(fade);runSpeed=Number(runSpeed);
 if(!Number.isFinite(fade)||fade<0.05||fade>1.5)throw Error('Transition duration must be 0.05-1.5 seconds.');
 if(!Number.isFinite(runSpeed)||runSpeed<4||runSpeed>80)throw Error('Run threshold must be 4-80 studs per second.');
 const assetNames=Object.values(assets);
 const lines=[
  '-- Generated by Mr H Moveset Maker for Uhhhhhh Reanimate.',
  '-- Each .anim file is a Uhhhhhh binary Track, not a published Roblox AnimationId.',
  '-- Review user-submitted scripts before executing any downloaded module.',
  'local modules = {}',
  'table.insert(modules, function()',
  '    local m = {}',
  '    m.ModuleType = "MOVESET"',
  '    m.Name = '+lua(name.trim()),
  '    m.InternalName = '+lua('MRH_'+safe.toUpperCase()),
  '    m.Description = "Custom R6 idle, walk and optional movement animations."',
  '    m.Assets = {'+assetNames.map(lua).join(', ')+'}',
  '    m.Config = function(parent) end',
  '    local files = {',
  ...ROLES.filter(role=>assets[role]).map(role=>'        '+role+' = '+lua(assets[role])+','),
  '    }',
  '    local fadeSeconds = '+fade.toFixed(3),
  '    local runThreshold = '+runSpeed.toFixed(2),
  '    local animators = {}',
  '    local timeByState = {}',
  '    local currentState = nil',
  '    local previousState = nil',
  '    local transitionTime = 0',
  '    local function existing(state)',
  '        if animators[state] then return state end',
  '        if state == "run" then return animators.walk and "walk" or "idle" end',
  '        if state == "jump" then return "idle" end',
  '        if state == "fall" then return animators.jump and "jump" or "idle" end',
  '        if state == "climb" then return animators.walk and "walk" or "idle" end',
  '        if state == "sit" then return "idle" end',
  '        return "idle"',
  '    end',
  '    local function resolve(figure)',
  '        if not figure or figure:GetAttribute("IsDancing") then return nil end',
  '        local humanoid = figure:FindFirstChildOfClass("Humanoid")',
  '        if not humanoid then return nil end',
  '        local state = humanoid:GetState()',
  '        if state == Enum.HumanoidStateType.Seated then return existing("sit") end',
  '        if state == Enum.HumanoidStateType.Climbing then return existing("climb") end',
  '        if state == Enum.HumanoidStateType.Jumping then return existing("jump") end',
  '        if state == Enum.HumanoidStateType.Freefall or',
  '           state == Enum.HumanoidStateType.FallingDown then return existing("fall") end',
  '        if humanoid.MoveDirection.Magnitude > 0.05 then',
  '            local root = figure:FindFirstChild("HumanoidRootPart")',
  '            local speed = 0',
  '            if root then',
  '                local velocity = root.AssemblyLinearVelocity',
  '                speed = Vector3.new(velocity.X, 0, velocity.Z).Magnitude',
  '            end',
  '            if speed < 0.05 then speed = humanoid.WalkSpeed * humanoid.MoveDirection.Magnitude end',
  '            return existing(speed >= runThreshold and "run" or "walk")',
  '        end',
  '        return "idle"',
  '    end',
  '    m.Init = function(figure)',
  '        animators = {}',
  '        timeByState = {}',
  '        currentState = nil',
  '        previousState = nil',
  '        transitionTime = 0',
  '        for state, filename in pairs(files) do',
  '            local animator = AnimLib.Animator.new()',
  '            animator.rig = figure',
  '            animator.track = AnimLib.Track.fromfile(AssetGetPathFromFilename(filename))',
  '            animator.looped = (state ~= "jump")',
  '            animator.speed = 1',
  '            animator.weight = 1',
  '            animators[state] = animator',
  '            timeByState[state] = 0',
  '        end',
  ...(assets.music?[
  '        SetOverrideMovesetMusic(AssetGetContentId('+lua(assets.music)+'), '+lua(name.trim())+', 1)'
  ]:[]),
  '    end',
  '    m.Update = function(dt, figure)',
  '        local desired = resolve(figure)',
  '        if not desired or not animators[desired] then return end',
  '        dt = math.clamp(tonumber(dt) or 0, 0, 0.1)',
  '        if desired ~= currentState then',
  '            previousState = currentState',
  '            currentState = desired',
  '            transitionTime = 0',
  '            timeByState[currentState] = 0',
  '        end',
  '        timeByState[currentState] = (timeByState[currentState] or 0) + dt',
  '        transitionTime += dt',
  '        local active = animators[currentState]',
  '        local alpha = math.clamp(transitionTime / fadeSeconds, 0, 1)',
  '        if previousState and previousState ~= currentState and',
  '           animators[previousState] and alpha < 1 then',
  '            local prev = animators[previousState]',
  '            prev.weight = 1',
  '            prev:Step(timeByState[previousState] or 0)',
  '            active.weight = alpha',
  '            active:Step(timeByState[currentState])',
  '        else',
  '            previousState = nil',
  '            active.weight = 1',
  '            active:Step(timeByState[currentState])',
  '        end',
  '    end',
  '    m.Destroy = function(figure)',
  '        animators = {}',
  '        timeByState = {}',
  '        currentState = nil',
  '        previousState = nil',
  ...(assets.music?['        SetOverrideMovesetMusic(nil)']:[]),
  '    end',
  '    return m',
  'end)',
  'return modules',
  ''
 ];
 return {filename:'MRH_'+safe+'_Moveset.lua',assets,source:lines.join('\n')};
}
module.exports={makeMoveset,ROLES};
